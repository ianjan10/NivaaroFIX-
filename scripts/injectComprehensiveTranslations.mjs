async function updateDataFile(filePath) {
  const moduleUrl = pathToFileURL(filePath).href;
  const mod = await import(moduleUrl);
  const supportedLanguages = mod.supportedLanguages;
  const currentTranslations = { ...mod.translations };

  for (const [lang, tokens] of Object.entries(proTranslations)) {
    if (!currentTranslations[lang]) {
      currentTranslations[lang] = {};
    }
    currentTranslations[lang] = {
      ...currentTranslations[lang],
      ...tokens
    };
  }

  const output = `export const supportedLanguages = ${JSON.stringify(supportedLanguages, null, 2)};\n\nexport const translations = ${JSON.stringify(currentTranslations, null, 2)};\n`;

  fs.writeFileSync(filePath, output, 'utf-8');
  console.log(`Successfully updated: ${filePath}`);
}

